function makePlaceholderTranslations(value) {
  if (typeof value === 'string') return `[मराठी अनुवाद आवश्यक] ${value}`;
  return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, makePlaceholderTranslations(entry)]));
}

